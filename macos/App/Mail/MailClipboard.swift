import AppKit

/// The general clipboard, behind a protocol so tests never touch the Owner's.
protocol Pasteboard: AnyObject, Sendable {
    var changeCount: Int { get }
    /// Every item, as its types' data.
    func snapshot() -> [[String: Data]]
    /// Replaces the contents; returns the change count after.
    func replace(with items: [[String: Data]]) -> Int
}

/// Lends the Owner's clipboard for one paste into Mail's window (plan D6, security review
/// 2026-10-30), used only where Accessibility can't put the content in directly (files, and text
/// Mail didn't take that way):
/// - what Latchkey puts there is marked transient, concealed, and generated (nspasteboard.org's
///   markers), so clipboard managers and history tools don't keep it;
/// - the Owner's clipboard is saved first and put back right after the paste;
/// - if anything else wrote to the clipboard meanwhile, nothing is pasted and their copy is kept.
final class ClipboardLoan: @unchecked Sendable {
    static let marks = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
    ]
    static let text = NSPasteboard.PasteboardType.string.rawValue
    static let fileURL = NSPasteboard.PasteboardType.fileURL.rawValue

    private let board: any Pasteboard
    private let saved: [[String: Data]]
    private let ours: Int
    private var returned = false

    init(_ board: any Pasteboard, items: [[String: Data]]) {
        self.board = board
        saved = board.snapshot()
        let marked = items.map { item in
            item.merging(Self.marks.map { ($0, Data()) }) { a, _ in a }
        }
        ours = board.replace(with: marked)
    }

    static func text(_ s: String) -> [[String: Data]] { [[text: Data(s.utf8)]] }

    static func files(_ urls: [URL]) -> [[String: Data]] {
        urls.map { [fileURL: Data($0.absoluteString.utf8)] }
    }

    /// The clipboard still holds only what Latchkey put there: checked right before Paste.
    var intact: Bool { board.changeCount == ours }

    /// Puts the Owner's clipboard back, unless someone copied something meanwhile (theirs stays).
    func giveBack() {
        guard !returned else { return }
        returned = true
        if intact { _ = board.replace(with: saved) }
    }
}

/// The Mac's general clipboard.
final class GeneralPasteboard: Pasteboard, @unchecked Sendable {
    private var pb: NSPasteboard { .general }

    var changeCount: Int { pb.changeCount }

    func snapshot() -> [[String: Data]] {
        (pb.pasteboardItems ?? []).map { item in
            var d: [String: Data] = [:]
            for t in item.types { if let v = item.data(forType: t) { d[t.rawValue] = v } }
            return d
        }
    }

    func replace(with items: [[String: Data]]) -> Int {
        pb.clearContents()
        let objects = items.map { d in
            let item = NSPasteboardItem()
            for (t, v) in d { item.setData(v, forType: NSPasteboard.PasteboardType(t)) }
            return item
        }
        if !objects.isEmpty { pb.writeObjects(objects) }
        return pb.changeCount
    }
}
